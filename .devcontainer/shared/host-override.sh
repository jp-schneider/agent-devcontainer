#!/usr/bin/env bash
# Writes the host-specific compose overlay (listed last in each variant's
# dockerComposeFile). Runs on the host, called from initialize.sh.
# Must stay bash 3.2 compatible (macOS system bash).
#
# Usage: host-override.sh <output-file>
# PROC_VERSION / WSL_LIB_DIR override the kernel version file and the WSL library dir checked
# for existence (test hooks only; the generated mount is always /usr/lib/wsl).
set -uo pipefail

out="$1"
mkdir -p "$(dirname "$out")"

if grep -qi microsoft "${PROC_VERSION:-/proc/version}" 2>/dev/null && [ -d "${WSL_LIB_DIR:-/usr/lib/wsl}" ]; then
    echo "host-override: WSL detected, mounting /usr/lib/wsl"
    cat > "$out" <<'EOF'
# Auto-generated by .devcontainer/shared/host-override.sh, do not edit. Host: WSL
services:
  claude-code:
    volumes:
      # WSL2 GPU libraries — provides current libdxcore.so and CUDA WSL2 drivers from the Windows NVIDIA driver
      - /usr/lib/wsl:/usr/lib/wsl:ro
EOF
else
    echo "host-override: no host-specific overrides"
    cat > "$out" <<'EOF'
# Auto-generated by .devcontainer/shared/host-override.sh, do not edit. Host: generic
services: {}
EOF
fi
