#!/usr/bin/env bash
# node toolchain, host-side init. Called by initialize.sh from the workspace root, after it created
# .devcontainer/.generated/ and an empty mountpoints.txt.
# Must stay bash 3.2 compatible (macOS system bash).
#
# Every package dir (a directory with a package.json, not inside node_modules or a hidden
# directory) gets its own named volume, mounted directly at /app/<dir>/node_modules. Not a symlink
# into one volume like the uv venvs: npm/pnpm workspaces link packages with relative symlinks,
# which would then resolve against the volume instead of /app. Writes:
# - .devcontainer/.generated/compose.node.yml: the volumes and their mounts (always written)
# - .devcontainer/.generated/mountpoints.txt: appends the mount targets; the image creates them as
#   the user, so the fresh volumes are user-owned
# - <dir>/node_modules on the host, if missing: Docker would otherwise create the mount point
#   root-owned in the workspace. The host's own node_modules is not touched, only hidden in the container.
# A new package dir needs a container rebuild (new mount, new image mount point).
#
# Usage: init-host.sh <env-file>
set -uo pipefail

env_file="$1"
gen=.devcontainer/.generated
out="$gen/compose.node.yml"

prefix="$(sed -n 's/^RESOURCE_PREFIX=//p' "$env_file" | tail -n 1)"
prefix="${prefix:-agent-sandbox}"
# Shared across all projects, hence external in compose.yml and created here (idempotent)
docker volume create "$prefix-node-fnm" > /dev/null
docker volume create "$prefix-node-cache" > /dev/null

# "<slug> <dir>" per package dir, dir relative to the workspace root ("" for the root)
entries=""
seen=" "
while IFS= read -r pkg; do
    dir="$(dirname "$pkg")"
    dir="${dir#.}"
    dir="${dir#/}"
    # Restricted to characters that are safe unquoted in the YAML below and in compose interpolation
    case "$dir" in
        *[!A-Za-z0-9._@+/-]*)
            echo "node init-host: WARNING skipping package dir '$dir' (unsupported characters in path)" >&2
            continue
            ;;
    esac
    if [ -n "$dir" ]; then nm="$dir/node_modules"; else nm=node_modules; fi
    if [ -L "$nm" ] || { [ -e "$nm" ] && [ ! -d "$nm" ]; }; then
        echo "node init-host: WARNING skipping $nm (exists and is not a directory)" >&2
        continue
    fi
    slug="$(printf '%s' "${dir:-root}" | tr '/' '_' | tr -c 'A-Za-z0-9_.-' '-')"
    case "$seen" in
        *" $slug "*)
            echo "node init-host: WARNING skipping $nm (volume name nm-$slug already used)" >&2
            continue
            ;;
    esac
    seen="$seen$slug "
    mkdir -p "$nm"
    echo "/app/$nm" >> "$gen/mountpoints.txt"
    entries="$entries$slug $dir
"
done < <(find . -mindepth 1 \( -name node_modules -o -name '.*' \) -prune -o -name package.json -type f -print \
    | LC_ALL=C sort)

{
    echo "# Auto-generated by .devcontainer/shared/toolchains/node/init-host.sh on each start; do not edit."
    echo "# One named volume per package dir, mounted at its node_modules."
    if [ -z "$entries" ]; then
        echo "services: {}"
    else
        echo "services:"
        echo "  claude-code:"
        echo "    volumes:"
        printf '%s' "$entries" | while read -r slug dir; do
            if [ -n "$dir" ]; then target="/app/$dir/node_modules"; else target=/app/node_modules; fi
            echo "      - type: volume"
            echo "        source: nm-$slug"
            echo "        target: $target"
        done
        echo "volumes:"
        printf '%s' "$entries" | while read -r slug dir; do
            echo "  nm-$slug:"
            echo "    name: \${RESOURCE_PREFIX:-agent-sandbox}-\${WORKTREE_NAME:-project}-nm-$slug"
        done
    fi
} > "$out"
echo "node init-host: $(printf '%s' "$entries" | grep -c .) package dir(s), wrote $out"
