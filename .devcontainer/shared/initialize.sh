#!/usr/bin/env bash
set -uo pipefail
# Runs on the host from the workspace root (devcontainer initializeCommand).
# Usage: initialize.sh <variant> [<toolchain>...]   e.g. "python-uv-gpu uv" or "python-uv-cpu uv node";
# omit the toolchains for core only. Toolchains are set up (host init, image install, post-start) in
# the order given.

VARIANT="${1:-}"
[ $# -gt 0 ] && shift
TOOLCHAINS="$*"

for t in $TOOLCHAINS; do
    if [ ! -d ".devcontainer/shared/toolchains/$t" ]; then
        echo "initialize: ERROR unknown toolchain '$t' (no .devcontainer/shared/toolchains/$t/)" >&2
        exit 1
    fi
done

echo "Initializing devcontainer environment..."

mkdir -p .devcontainer/shared .claude-docker
# Root .env: host-only config (masked inside the container); container.env: passed to the container
if [ ! -f .env ]; then
    echo "No .env file found in the root of the repository."
    echo "Creating a new .env file..."
    touch .env
fi
if [ ! -f container.env ]; then
    echo "Creating an empty container.env (environment variables for the container)..."
    touch container.env
fi

echo "Recreating .devcontainer/shared/.env file..."
echo "Writing environment variables to .devcontainer/shared/.env..."
echo "# This file is auto-generated by .devcontainer/shared/initialize.sh and will be overwritten on each initialization." > .devcontainer/shared/.env
echo "# Written at $(date)" >> .devcontainer/shared/.env
# DEVCONTAINER_* lines from the root .env (host-only), unchanged, usable as ${DEVCONTAINER_*} in
# compose files. The prefix keeps them apart from the host's own variables (e.g. DATA_PATH locally vs.
# DEVCONTAINER_DATA_PATH for the container) and from compose's own COMPOSE_* settings; other .env
# lines are not copied. This file is masked inside the container.
grep -E '^DEVCONTAINER_[A-Za-z0-9_]+=' .env >> .devcontainer/shared/.env 2> /dev/null || true
echo "WORKTREE_NAME=$(basename "$PWD")" >> .devcontainer/shared/.env
# Compose project names allow only [a-z0-9_-]; lowercase and strip the rest
echo "PROJECT_SLUG=$(basename "$PWD" | tr '[:upper:]' '[:lower:]' | tr -cd 'a-z0-9_-')" >> .devcontainer/shared/.env

echo "GIT_MAIN_REPO_PATH=$(realpath "$(git rev-parse --git-common-dir 2>/dev/null)/.." 2>/dev/null || echo "$PWD")" >> .devcontainer/shared/.env
echo "LOCAL_WORKSPACE_FOLDER=$PWD" >> .devcontainer/shared/.env
echo "HOST_HOME=$HOME" >> .devcontainer/shared/.env
echo "HOST_UID=$(id -u)" >> .devcontainer/shared/.env
echo "HOST_GID=$(id -g)" >> .devcontainer/shared/.env
# The variant's toolchains: build arg (Dockerfile) and DEVCONTAINER_TOOLCHAINS (shared/post-start.sh)
echo "TOOLCHAINS=\"$TOOLCHAINS\"" >> .devcontainer/shared/.env
# Name prefix for new Docker resources (volumes of the node toolchain); older resources keep their
# claude-code-* names
echo "RESOURCE_PREFIX=agent-sandbox" >> .devcontainer/shared/.env

mkdir -p .devcontainer/.generated
# Directories under /app that the image creates as the user (Dockerfile): mount points of named
# volumes, which take the ownership of that directory on first mount. Toolchain init-host.sh
# scripts append to it. Always written, so the Dockerfile can COPY it.
: > .devcontainer/.generated/mountpoints.txt

# A toolchain whose overlay is missing from the variant's compose list would be installed in the
# image without its volumes and environment (same extraction as resolve-config.sh)
compose_list=""
if [ -f ".devcontainer/$VARIANT/devcontainer.json" ]; then
    compose_list="$(awk '/"dockerComposeFile"[[:space:]]*:/ {f = 1} f {print} f && /\]/ {exit}' \
        ".devcontainer/$VARIANT/devcontainer.json")"
fi
# Toolchain host-side hooks (toolchains/<name>/init-host.sh), toolchains passed by the variant
for t in $TOOLCHAINS; do
    case "$compose_list" in
        *"shared/toolchains/$t/compose.yml"*) ;;
        *) echo "initialize: WARNING toolchain $t: shared/toolchains/$t/compose.yml is not in the dockerComposeFile list of $VARIANT" >&2 ;;
    esac
    if [ -f ".devcontainer/shared/toolchains/$t/init-host.sh" ]; then
        echo "Running $t toolchain host init..."
        bash ".devcontainer/shared/toolchains/$t/init-host.sh" .devcontainer/shared/.env
    fi
done

# Extra system packages for the image: project-wide + variant-specific lists, comments stripped,
# one package (optionally "pkg=version") per line. Always written, so the Dockerfile can COPY it.
for f in .devcontainer/apt-packages.txt ".devcontainer/$VARIANT/apt-packages.txt"; do
    [ -n "$VARIANT" ] || [ "$f" = .devcontainer/apt-packages.txt ] || continue
    [ -f "$f" ] && sed 's/#.*//' "$f"
done | tr -s '[:space:]' '\n' | sed '/^$/d' > .devcontainer/.generated/apt-packages.txt

bash .devcontainer/shared/host-override.sh .devcontainer/.generated/compose.host.yml
# Read-only protection of host-executed paths; aborts the start on planted nested repos
bash .devcontainer/shared/protect-paths.sh .devcontainer/.generated/compose.protect.yml || exit 1
# Fully merged compose config of this variant, for inspection (warns only)
if [ -n "$VARIANT" ]; then
    bash .devcontainer/shared/resolve-config.sh "$VARIANT" .devcontainer/.generated/compose.resolved.yml
fi
echo "Done."

echo "Creating .claude-docker directory and files..."
touch .claude-docker/.bash_history
[ -f .claude-docker/.claude.json ] || echo '{}' > .claude-docker/.claude.json
echo "Done."

echo "Initialization complete."