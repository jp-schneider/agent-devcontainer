#!/usr/bin/env bash
# Writes the fully merged compose config of a variant (`docker compose config`) for
# debugging and reproducibility. Not used to start the container. The devcontainer
# CLI adds its own build/feature overrides on top, so its effective config differs slightly.
# Note: env_file contents (container.env, shared/.env) are inlined into the output.
#
# Runs on the host from the workspace root, called from initialize.sh after the
# generated overlays exist. Only warns on failure.
# Must stay bash 3.2 compatible (macOS system bash).
#
# Usage: resolve-config.sh <variant> <output-file>
set -uo pipefail

variant="$1"
out="$2"
variant_dir=".devcontainer/$variant"
json="$variant_dir/devcontainer.json"

if [ ! -f "$json" ]; then
    echo "resolve-config: WARNING $json not found, skipping" >&2
    exit 0
fi

# The dockerComposeFile array, one quoted path per line (devcontainer.json is JSONC,
# so no JSON parser); paths are relative to the variant dir
files="$(awk '/"dockerComposeFile"[[:space:]]*:/ {f = 1} f {print} f && /\]/ {exit}' "$json" \
    | grep -oE '"[^"]+\.ya?ml"' | tr -d '"')"
if [ -z "$files" ]; then
    echo "resolve-config: WARNING no dockerComposeFile entries found in $json, skipping" >&2
    exit 0
fi

set --
for f in $files; do
    set -- "$@" -f "$variant_dir/$f"
done

mkdir -p "$(dirname "$out")"
if {
    echo "# Auto-generated by .devcontainer/shared/resolve-config.sh: 'docker compose config' of variant $variant."
    echo "# Written at $(date). For inspection only; not used to start the container."
    docker compose "$@" config
} > "$out.tmp" 2> "$out.err"; then
    mv "$out.tmp" "$out"
    rm -f "$out.err"
    echo "resolve-config: wrote $out"
else
    echo "resolve-config: WARNING 'docker compose config' failed:" >&2
    cat "$out.err" >&2
    rm -f "$out.tmp" "$out.err"
fi
